def load_split(rows, split, heads=None, label=None):
    """Return list of (array[2,256,256], y:int, head:int) for the matching rows."""
    out = []
    for r in rows:
        if r["split"] != split:
            continue
        if heads is not None and int(r["head"]) not in heads:
            continue
        if label is not None and r["label"] != label:
            continue
        arr = np.load(os.path.join(CACHE, r["cache"]))
        out.append((arr, int(r["y"]), int(r["head"])))
    return out


