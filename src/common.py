# 4. NORMALISATION for the classifier
# ============================================================================
def channel_stats(arrays):
    """mean/std per (real-imag channel, antenna-pair row), averaged over freq+samples.
    Shapes -> [2,256,1]. This removes the common-mode clutter level of each channel."""
    stack = np.stack(arrays, 0)                   # [N,2,256,256]
    mean = stack.mean(axis=(0, 3))                # [2,256]
    std = stack.std(axis=(0, 3)) + 1e-8           # [2,256]
    return mean[..., None].astype(np.float32), std[..., None].astype(np.float32)


def standardize(arr, mean, std):
    return (arr - mean) / std


# ============================================================================
# 5. THE LEFT-RIGHT SYMMETRY FEATURE  (this is what makes Phase 2 work)
# ============================================================================
def find_mirror_axis(healthy_arrays):
    """Find the mirror m that makes the HEALTHY scans most symmetric, using the
    permutation P(k) = (m - k) mod 16. A bleed is one-sided so it breaks this
    symmetry; the skull clutter is (mostly) symmetric so it cancels."""
    def to_grid(a):
        return (a[0] + 1j * a[1]).reshape(16, 16, -1)
    grids = [to_grid(a) for a in healthy_arrays]
    best_m, best_s = 0, 1e9
    for m in range(16):
        idx = [(m - k) % 16 for k in range(16)]
        s = np.mean([np.abs(g - g[np.ix_(idx, idx)]).mean() for g in grids])
        if s < best_s:
            best_s, best_m = s, m
    return best_m


def mirror_asym(arr, m):
    """arr [2,256,256] -> the asymmetry S - P S P, kept as [2,256,256] (real, imag)."""
    g = (arr[0] + 1j * arr[1]).reshape(16, 16, -1)
    idx = [(m - k) % 16 for k in range(16)]
    d = g - g[np.ix_(idx, idx)]
    d = d.reshape(256, -1)
    return np.stack([d.real, d.imag], axis=0).astype(np.float32)


def make_transform(kind, m):
    """Return f(arr[2,256,256]) -> repr[C,256,256] for kind in {raw, asym, raw+asym}."""
    if kind == "raw":
        return lambda a: a
    if kind == "asym":
        return lambda a: mirror_asym(a, m)
    if kind == "raw+asym":
        return lambda a: np.concatenate([a, mirror_asym(a, m)], axis=0)
    raise ValueError(kind)


# ============================================================================
# 6. THE SMALL CNN CLASSIFIER  (used for the before/after comparison)
# ============================================================================
class SParamCNN(nn.Module):
    def __init__(self, in_ch=2, p_drop=0.3):
        super().__init__()
        def block(i, o):
            return nn.Sequential(
                nn.Conv2d(i, o, 3, padding=1), nn.BatchNorm2d(o), nn.ReLU(inplace=True),
                nn.MaxPool2d(2))
        self.features = nn.Sequential(
            block(in_ch, 16), block(16, 32), block(32, 64),
            nn.Conv2d(64, 64, 3, padding=1), nn.BatchNorm2d(64), nn.ReLU(inplace=True),
            nn.AdaptiveAvgPool2d(1))
        self.head = nn.Sequential(nn.Flatten(), nn.Dropout(p_drop), nn.Linear(64, 1))

    def forward(self, x):
        return self.head(self.features(x)).squeeze(1)


def _augment(x):
    """Mild, physically-sensible augmentation. I do NOT scramble the frequency axis,
    because the bleed's fingerprint sits at specific frequencies and a big roll would
    destroy the class signal. So just a tiny jitter and an optional +/-2 bin shift."""
    if np.random.rand() < 0.5:
        x = torch.roll(x, shifts=int(np.random.randint(-2, 3)), dims=-1)
    x = x + 0.02 * torch.randn_like(x)
    return x


def train_eval(train, val, test, mean, std, epochs=60, lr=1e-3, bs=16,
               seed=0, tag="phase2", verbose=True, in_ch=2):
    """train/val/test are lists of (arr, y, head). Returns metrics dict + model + history.
    `arr` may be any C-channel representation; set in_ch=C accordingly."""
    torch.manual_seed(seed); np.random.seed(seed)

    def to_tensors(ds):
        X = np.stack([standardize(a, mean, std) for a, _, _ in ds]).astype(np.float32)
        y = np.array([b for _, b, _ in ds], dtype=np.float32)
        return torch.tensor(X), torch.tensor(y)

    Xtr, ytr = to_tensors(train)
    Xva, yva = to_tensors(val)
    Xte, yte = to_tensors(test)

    model = SParamCNN(in_ch=in_ch).to(DEVICE)
    opt = torch.optim.Adam(model.parameters(), lr=lr, weight_decay=1e-4)
    sched = torch.optim.lr_scheduler.CosineAnnealingLR(opt, T_max=epochs)
    lossf = nn.BCEWithLogitsLoss()

    def accuracy(X, y):
        model.eval()
        with torch.no_grad():
            p = torch.sigmoid(model(X.to(DEVICE))).cpu().numpy()
        return float(((p > 0.5).astype(int) == y.numpy().astype(int)).mean())

    n = len(Xtr); best_va = -1; best_state = None; hist = []
    for ep in range(epochs):
        model.train()
        perm = torch.randperm(n)
        for i in range(0, n, bs):
            idx = perm[i:i + bs]
            xb = _augment(Xtr[idx]).to(DEVICE)
            yb = ytr[idx].to(DEVICE)
            opt.zero_grad()
            loss = lossf(model(xb), yb)
            loss.backward()
            torch.nn.utils.clip_grad_norm_(model.parameters(), 1.0)
            opt.step()
        sched.step()
        va = accuracy(Xva, yva); tr = accuracy(Xtr, ytr)
        hist.append({"epoch": ep, "train_acc": tr, "val_acc": va})
        if va >= best_va:
            best_va = va
            best_state = {k: v.cpu().clone() for k, v in model.state_dict().items()}
        if verbose and (ep % 5 == 0 or ep == epochs - 1):
            print(f"  ep{ep:02d}  train_acc={tr:.3f}  val_acc={va:.3f}  (best_val={best_va:.3f})")

    model.load_state_dict(best_state)
    metrics = {
        "tag": tag,
        "train_acc": accuracy(Xtr, ytr),
        "val_acc": accuracy(Xva, yva),
        "test_acc": accuracy(Xte, yte),
        "n_train": len(train), "n_val": len(val), "n_test": len(test),
    }
    return metrics, model, hist
