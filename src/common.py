def parse_name(path):
    """Pull the labels out of a filename. Works for BLOOD_* and HEALTHY_* files.
    The filename is our free label: it tells us bleed vs healthy, which head it is,
    and (for bleeds) where the blood sits and how big it is."""
    b = os.path.basename(path)
    info = {"path": path, "file": b}
    if b.upper().startswith("BLOOD"):
        info["label"] = "blood"            # 1 = has a bleed
        info["y"] = 1
        info["head"] = int(re.search(r"head(\d+)", b).group(1))
        m = re.search(r"_x(-?[\d.]+)_y(-?[\d.]+)_z(-?[\d.]+)_r([\d.]+)_v(\d+)", b)
        if m:
            info["bx"], info["by"], info["bz"] = float(m.group(1)), float(m.group(2)), float(m.group(3))
            info["radius"], info["volume"] = float(m.group(4)), int(m.group(5))
    else:
        info["label"] = "healthy"          # 0 = healthy
        info["y"] = 0
        info["head"] = int(re.search(r"HM(\d+)", b).group(1))
        rm = re.search(r"Run(\d+)", b)
        info["run"] = int(rm.group(1)) if rm else 0
    return info


def list_split(root, split):
    """Return (blood_files, healthy_files) for split in {train, test}."""
    blood = sorted(glob.glob(os.path.join(root, split, "Blood", "*.s16p")))
    healthy = sorted(glob.glob(os.path.join(root, split, "Healthy", "*.s16p")))
    return blood, healthy


def load_raw_S(path):
    """Load one .s16p file -> complex ndarray [F, 16, 16]. Uses scikit-rf."""
    import skrf
    return skrf.Network(path).s          # complex128 [F, 16, 16]


def S_to_image(S, f_out=F_OUT):
    """complex S [F,16,16] -> float32 image [2, 256, f_out] (channel0=real, channel1=imag).
    The frequency axis is linearly resampled to f_out points. Returns raw physical
    S units (no normalisation yet)."""
    from scipy.interpolate import interp1d
    F = S.shape[0]
    flat = S.reshape(F, N_PAIR).T            # [256, F]
    if F != f_out:
        x_old = np.linspace(0.0, 1.0, F)
        x_new = np.linspace(0.0, 1.0, f_out)
        flat = interp1d(x_old, flat, axis=1, kind="linear", assume_sorted=True)(x_new)
    return np.stack([flat.real, flat.imag], axis=0).astype(np.float32)   # [2,256,f_out]


def load_image(path, f_out=F_OUT):
    return S_to_image(load_raw_S(path), f_out=f_out)


