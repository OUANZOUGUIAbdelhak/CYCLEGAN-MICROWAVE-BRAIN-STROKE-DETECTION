"""
common.py  (shared helpers, used by every phase)
------------------------------------------------
This is the one place that knows about paths, reads the raw .s16p files, turns them
into the 2-channel [real, imag] images the networks eat, and holds the small pieces
that more than one phase needs (the mirror-symmetry feature and the little CNN
classifier). I kept all of this in a single file on purpose, so when I forget how
something works I only have one place to look.

The data representation, in one picture:

  raw S : complex array [F=1001, 16, 16]           (frequency, antenna, antenna)
    -> flatten the 16x16 antenna grid   -> [F, 256]
    -> transpose                         -> [256, F]      (256 antenna-pair rows)
    -> resample frequency F -> 256        -> [256, 256]
    -> stack (real, imag) as 2 channels   -> [2, 256, 256]  float32

I keep BOTH the real and the imaginary part (the paper uses magnitude only). That
keeps the phase, keeps the Blood - Healthy subtraction exact, and it is the only way
the Phase 6 physics checks are even possible.
"""
